import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { BRAND, luminance, markMarkup, parseColor, wordmarkMarkup } from "../src/lib/pipaya-logo";
import { WORDMARK_PATH, WORDMARK_W } from "../src/lib/wordmark-path";
import { LOGO_PARTS, parsePackage, STYLE_PARTS, UI_PARTS } from "../src/lib/extensions/schema";

describe("the pipaya logo is closed to themes", () => {
	const all = [
		...(["color", "solid", "watermark"] as const).flatMap((tone) => [true, false].map((dark) => markMarkup({ size: 26, tone, dark }))),
		wordmarkMarkup({ size: 16, dark: true }),
		wordmarkMarkup({ size: 16, dark: false }),
	];
	test("it reads no design token and no font", () => {
		for (const m of all) {
			expect(m).not.toContain("var(");
			expect(m).not.toMatch(/font|<text/i);
		}
	});
	test("its host box resets everything with !important and keeps only visibility and pointer-events from the page", () => {
		for (const m of all) {
			expect(m).toContain(":host{all:initial!important;");
			expect(m).toContain("visibility:inherit!important;pointer-events:inherit!important;");
			expect(m).not.toContain("color:inherit");
		}
	});
	test("brand colours: two-tone per backdrop, one ink for the solid mark and the wordmark", () => {
		const two = markMarkup({ size: 26, tone: "color", dark: true });
		for (const c of [BRAND.dark.trunk, BRAND.dark.leaf, BRAND.dark.fruit]) expect(two).toContain(`fill="${c}"`);
		expect(markMarkup({ size: 26, tone: "solid", dark: false })).toContain(`fill="${BRAND.light.ink}"`);
		expect(wordmarkMarkup({ size: 16, dark: true })).toContain(`fill="${BRAND.dark.ink}"`);
		expect(markMarkup({ size: 72, tone: "watermark", dark: false })).toContain(`fill="${BRAND.light.watermark}"`);
	});
	test("the icon form takes the colour of where it sits, like any icon", () => {
		const icon = markMarkup({ size: 18, tone: "current", dark: true });
		expect(icon).toContain('fill="currentColor"');
		expect(icon).toContain("color:inherit!important;");
	});
	test("sizes are literal: the wordmark is as tall as asked and as wide as its outlines", () => {
		const m = wordmarkMarkup({ size: 16, dark: true });
		expect(m).toContain(`width:${Math.round((16 * WORDMARK_W) / 10) / 100}px!important;height:16px!important;`);
		expect(markMarkup({ size: 26, tone: "color", dark: true })).toContain("width:26px!important;height:26px!important;");
	});
	test("the wordmark outlines are generated, from the bundled font", () => {
		expect(WORDMARK_W).toBe(3330); // 6 x 600 advance, -45 tracking after each letter
		expect(WORDMARK_PATH).toMatch(/^M[\d.]+ [\d.]+/);
		expect(readFileSync("src/lib/wordmark-path.ts", "utf8")).toStartWith("// Generated by logo/build_wordmark.py");
	});
	test("brand colours match logo/build_mark.py", () => {
		const py = readFileSync("../logo/build_mark.py", "utf8");
		for (const mode of ["dark", "light"] as const) {
			const line = py.split("\n").find((l) => l.startsWith(mode === "dark" ? "DARK =" : "LIGHT ="))!;
			for (const k of ["trunk", "leaf", "fruit"] as const) expect(line).toContain(`${k}="${BRAND[mode][k]}"`);
		}
	});
});

describe("backdrop", () => {
	test("colours are read the way a browser gives them back", () => {
		expect(parseColor("rgb(22, 22, 22)")).toEqual([22, 22, 22, 1]);
		expect(parseColor("rgba(255, 255, 255, 0.5)")).toEqual([255, 255, 255, 0.5]);
		expect(parseColor("rgb(255 255 255 / 40%)")).toEqual([255, 255, 255, 0.4]);
		expect(parseColor("#16161680")).toEqual([22, 22, 22, 128 / 255]);
		expect(parseColor("transparent")).toBeNull();
	});
	test("the app's own dark and light pages are told apart", () => {
		expect(luminance(0x16, 0x16, 0x16)).toBeLessThan(0.18);
		expect(luminance(0xff, 0xff, 0xff)).toBeGreaterThan(0.18);
		expect(luminance(0x1e, 0x12, 0x2c)).toBeLessThan(0.18); // a theme's dark purple sidebar
	});
});

describe("no extension hook reaches the logo", () => {
	test("sidebar.brand is no style hook, and its part is accepted (old packages install) but never drawn", () => {
		expect(STYLE_PARTS as readonly string[]).not.toContain("sidebar.brand");
		expect(LOGO_PARTS.has("sidebar.brand")).toBe(true);
		expect(UI_PARTS as readonly string[]).toContain("sidebar.brand");
		const manifest = { id: "my.brand", name: "Brand", version: "1.0.0", sdkVersion: 1, permissions: ["ui-components"] };
		expect(parsePackage({ manifest, components: { B: "<b>x</b>" }, replaces: { "sidebar.brand": "B" } }).replaces).toEqual({ "sidebar.brand": "B" });
	});
	test("the logo's places carry no part or extension slot, and the empty screens keep the mark outside their part", () => {
		const sidebar = readFileSync("src/components/shell/Sidebar.svelte", "utf8");
		const row = sidebar.slice(sidebar.indexOf('<div class="brandrow"'), sidebar.indexOf("</div>", sidebar.indexOf('<div class="brandrow"')));
		expect(row).toContain("data-logo-frame");
		expect(row).not.toMatch(/ExtensionPart|ExtensionMount|data-part/);
		for (const f of ["src/components/shell/Welcome.svelte", "src/components/chat/EmptyHero.svelte"]) {
			const src = readFileSync(f, "utf8");
			const part = src.slice(src.indexOf("<ExtensionPart"), src.indexOf("</ExtensionPart>"));
			expect(part).not.toContain("PipayaMark");
			expect(src).toMatch(/class="face" data-logo-frame/);
		}
		expect(readFileSync("src/components/shell/Pane.svelte", "utf8")).not.toContain("ExtensionPart");
	});
	test("every brand placement is tagged for the style guard", () => {
		expect(readFileSync("src/components/ui/Wordmark.svelte", "utf8")).toContain("data-pipaya-logo");
		expect(readFileSync("src/components/ui/PipayaMark.svelte", "utf8")).toContain('data-pipaya-logo={tone === "current" ? undefined : ""}');
	});
});
