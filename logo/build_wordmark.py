#!/usr/bin/env python3
"""pipaya 워드마크: "pipaya"를 JetBrains Mono 600(앱 번들 폰트)의 글리프 윤곽선으로 고정한다.

글자로 그리면 확장 테마가 --mono 토큰이나 같은 이름의 @font-face로 워드마크 글꼴을 바꿀 수 있다. 그래서 앱은 이 경로를
그리고(client/src/components/ui/Wordmark.svelte), 어떤 폰트 설정도 워드마크에 닿지 않는다.

기하: 글자 간격 -0.045em, 상자 높이 1em(line-height 1), 기준선은 위에서 0.86em(폰트 ascent 1020 · descent 300을
1em 줄 상자에 넣은 위치). 예전 텍스트 워드마크와 같은 상자다.

실행: python3 logo/build_wordmark.py   (fontTools, brotli 필요)
  -> client/src/lib/wordmark-path.ts
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "client/public/fonts/jetbrainsmono-variable.woff2"
OUT = ROOT / "client/src/lib/wordmark-path.ts"
TEXT = "pipaya"
WEIGHT = 600
TRACKING = -45  # letter-spacing -0.045em, in 1000-unit em (applied after every letter, the last one too, like CSS)
BASELINE = 860  # from the top of the 1em box: line-height 1 with ascent 1020 + descent 300 leaves -160 above


def num(v: float) -> str:
    return f"{v:.1f}".rstrip("0").rstrip(".")


def main():
    font = instantiateVariableFont(TTFont(FONT), {"wght": WEIGHT})
    upem = font["head"].unitsPerEm
    assert upem == 1000, upem
    cmap, glyphs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    x = 0
    parts = []
    for ch in TEXT:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=num)
        # font units are y-up with the baseline at 0; the SVG box is y-down with the baseline at BASELINE
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, BASELINE)))
        parts.append(pen.getCommands())
        x += hmtx[name][0] + TRACKING
    OUT.write_text(
        "// Generated by logo/build_wordmark.py from client/public/fonts/jetbrainsmono-variable.woff2 (wght 600). Do not edit.\n"
        "/** The pipaya wordmark as outlines, in a 1000-unit em: the box is WORDMARK_W wide and 1000 tall (baseline at 860). */\n"
        f"export const WORDMARK_W = {x};\n"
        f"export const WORDMARK_PATH = {repr(''.join(parts))};\n"
    )
    print(f"{OUT.relative_to(ROOT)}: {x} x 1000, {len(''.join(parts))} chars")


if __name__ == "__main__":
    main()
